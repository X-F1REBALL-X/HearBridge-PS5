#!/usr/bin/env python3
"""Embed Realtek USB Bluetooth firmware from assets/firmware as a C array
header (src/rtl_fw_blobs.h). Blobs come from linux-firmware rtl_bt/
(LICENCE.rtlwifi_firmware.txt). Developed by X-F1REBALL-X."""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DIR = os.path.join(ROOT, "assets", "firmware")
DST = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "rtl_fw_blobs.h")

# Only the files listed here are shipped in the ELF. Keep this short so the
# payload stays small; other chips can still use a manual copy under
# /data/hearbridge/firmware/.
BUNDLED = [
    "rtl8761bu_fw.bin",
    "rtl8761bu_config.bin",
]

def c_array(name, data):
    rows = [", ".join("0x%02x" % c for c in data[i:i + 16]) for i in range(0, len(data), 16)]
    body = ",\n    ".join(rows) if rows else ""
    return (
        "static const unsigned char %s[%d] = {\n    %s\n};\n"
        % (name, len(data), body)
    )

blobs = []
parts = [
    "/* Generated by scripts/gen_rtl_fw.py from assets/firmware. Do not edit.\n"
    " * Realtek USB Bluetooth firmware from linux-firmware rtl_bt/.\n"
    " * Licence: assets/firmware/LICENCE.rtlwifi_firmware.txt. */\n"
    "#ifndef HB_RTL_FW_BLOBS_H\n#define HB_RTL_FW_BLOBS_H\n\n"
    "#include <stddef.h>\n\n"
    "typedef struct {\n"
    "    const char *name;\n"
    "    const unsigned char *data;\n"
    "    size_t len;\n"
    "} hb_rtl_fw_blob;\n\n"
]

for i, fname in enumerate(BUNDLED):
    path = os.path.join(SRC_DIR, fname)
    data = open(path, "rb").read()
    sym = "hb_rtl_fw_blob_%d" % i
    parts.append(c_array(sym, data))
    parts.append("\n")
    blobs.append((fname, sym, len(data)))

parts.append("static const hb_rtl_fw_blob hb_rtl_fw_blobs[] = {\n")
for fname, sym, n in blobs:
    parts.append('    { "%s", %s, %du },\n' % (fname, sym, n))
parts.append("};\n\n")
parts.append(
    "#define HB_RTL_FW_BLOB_COUNT (sizeof hb_rtl_fw_blobs / sizeof hb_rtl_fw_blobs[0])\n\n"
    "#endif\n"
)

os.makedirs(os.path.dirname(DST) or ".", exist_ok=True)
open(DST, "w").write("".join(parts))
print("wrote %s (%d blobs, %d bytes)" % (DST, len(blobs), sum(n for _, _, n in blobs)))
